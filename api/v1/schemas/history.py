class ReportDetails(BaseModel):
    """พื้นที่รายละเอียดรายงาน"""

    news_content: Optional[str] = Field(None, description="สรุปข่าวสาร")
    empty_news_disclosure: Optional[str] = Field(
        None,
        description="การเปิดเผยข้อมูลให้ผู้ใช้เห็นเมื่อการค้นหาข่าวไม่ได้ดำเนินการหรือไม่มีผลลัพธ์",
    )
    raw_result: Optional[Any] = Field(None, description="ผลลัพธ์การวิเคราะห์ต้นฉบับ (JSON)")
    context_snapshot: Optional[Any] = Field(None, description="ภาพถ่ายบริบทขณะวิเคราะห์ (JSON)")
    analysis_context_pack_overview: Optional[AnalysisContextPackOverview] = Field(
        None,
        description="สรุปบริบทนำเข้าสำหรับการวิเคราะห์ครั้งนี้ (ละเอียดอ่อน)",
    )
    financial_report: Optional[Any] = Field(None, description="สรุปงบการเงินในรูปแบบโครงสร้าง (มาจาก fundamental_context)")
    dividend_metrics: Optional[Any] = Field(None, description="ตัวชี้วัดการจ่ายเงินปันผลในรูปแบบโครงสร้าง (รวม TTM)")
    belong_boards: Optional[Any] = Field(None, description="รายการกลุ่มอุตสาหกรรมที่เกี่ยวข้อง")
    sector_rankings: Optional[Any] = Field(None, description="ตารางอันดับผลกำไรขาดทุนของกลุ่มอุตสาหกรรม (โครงสร้าง {top, bottom})")
    concept_rankings: Optional[Any] = Field(None, description="แนวโน้มการเปลี่ยนแปลงของกลุ่มธุรกิจ (โครงสร้าง {top, bottom})")
    market_structure: Optional[Any] = Field(None, description="บริบทโครงสร้างตลาด (ชั้นธีม + ตำแหน่งหุ้นรายตัว)")

    @model_validator(mode="after")
    def populate_context_derived_details(self) -> "ReportDetails":
        if self.concept_rankings is None and self.context_snapshot is not None:
            try:
                from src.utils.data_processing import extract_board_detail_fields

                extracted = extract_board_detail_fields(self.context_snapshot)
                self.concept_rankings = extracted.get("concept_rankings")
            except Exception:
                self.concept_rankings = None
        if self.market_structure is None:
            try:
                from src.utils.data_processing import extract_market_structure_detail_field

                self.market_structure = extract_market_structure_detail_field(
                    self.context_snapshot,
                    self.raw_result,
                )
            except Exception:
                self.market_structure = None
        return self


